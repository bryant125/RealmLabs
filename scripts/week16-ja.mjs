// CJK text has no spaces, so count characters for CJK and words for Latin text (same as scripts/lib/intl-draft.mjs).
function size(body) {
  let cjk = 0, words = 0
  for (const b of body) if (b._type === 'block') for (const s of b.children || []) {
    const t = s.text || ''
    cjk += (t.match(/[぀-ヿ㐀-鿿가-힯]/g) || []).length
    words += t.replace(/[぀-ヿ㐀-鿿가-힯]/g, ' ').split(/\s+/).filter(Boolean).length
  }
  return {cjk, words}
}

