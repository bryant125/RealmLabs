“今天才喝了500毫升，是不是太少了？”这大概是新手爸妈问得最多的问题。网上的新生儿奶量标准表很多，数字却各不相同。这篇按国家卫健委2024年印发的喂养评估指南和中国营养学会《中国婴幼儿膳食指南（2022）》整理，告诉你每个月龄大概喝多少、一天喂几次，以及怎么记录才看得出宝宝到底吃没吃够。
